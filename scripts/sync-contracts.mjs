#!/usr/bin/env node
// Copies generated contract code out of the pinned `contracts` submodule
// (OracleDesk-SmartContract) into src/generated/, so the build never imports
// from the submodule directly.
//
//   node scripts/sync-contracts.mjs          # write the files
//   node scripts/sync-contracts.mjs --check  # exit 1 if any file is stale
//
// After bumping the submodule (`git -C contracts checkout <commit>`), run the
// sync and commit both the submodule pointer and src/generated/.

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SUBMODULE = join(ROOT, "contracts");
const SOURCE = join(SUBMODULE, "oracledesk-stellar");
const DEST = join(ROOT, "src", "generated");

// [source path under oracledesk-stellar/, destination file name]
const FILES = [
  ["packages/bindings/market-core/src/index.ts", "market-core.ts"],
  ["packages/bindings/treasury/src/index.ts", "treasury.ts"],
  ["packages/bindings/reasoning-registry/src/index.ts", "reasoning-registry.ts"],
  ["packages/bindings/resolver/src/index.ts", "resolver.ts"],
  ["agents/core/fpmm.ts", "fpmm.ts"],
  ["deployments/testnet.json", "deployments.testnet.json"],
];

const check = process.argv.includes("--check");

if (!existsSync(SOURCE)) {
  console.error(
    `contracts submodule not found at ${relative(ROOT, SOURCE)}.\n` +
      "Run: git submodule update --init",
  );
  process.exit(2);
}

const commit = execFileSync("git", ["-C", SUBMODULE, "rev-parse", "HEAD"], {
  encoding: "utf8",
}).trim();

function render(src, contents) {
  if (src.endsWith(".json")) return contents;
  const header =
    `// AUTO-GENERATED by scripts/sync-contracts.mjs. DO NOT EDIT.\n` +
    `// Source: OracleDesk-SmartContract@${commit} oracledesk-stellar/${src}\n` +
    `// Regenerate with: npm run sync:contracts\n` +
    `// @ts-nocheck\n`;
  return header + contents;
}

let stale = 0;
mkdirSync(DEST, { recursive: true });

for (const [src, name] of FILES) {
  const from = join(SOURCE, src);
  const to = join(DEST, name);
  const expected = render(src, readFileSync(from, "utf8"));
  const current = existsSync(to) ? readFileSync(to, "utf8") : null;

  if (current === expected) {
    if (!check) console.log(`up to date  ${relative(ROOT, to)}`);
    continue;
  }
  if (check) {
    console.error(`stale       ${relative(ROOT, to)}  (from ${src})`);
    stale++;
    continue;
  }
  writeFileSync(to, expected);
  console.log(`wrote       ${relative(ROOT, to)}`);
}

if (check) {
  if (stale > 0) {
    console.error(`\n${stale} generated file(s) are stale. Run: npm run sync:contracts`);
    process.exit(1);
  }
  console.log(`generated files match contracts@${commit.slice(0, 7)}`);
}
